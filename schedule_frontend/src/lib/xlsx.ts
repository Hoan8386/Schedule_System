/**
 * Ghi file Excel (.xlsx) tối giản không cần thư viện: một sheet, dòng tiêu đề in đậm,
 * ô chữ dạng inline string, ô số dạng number. File .xlsx là gói zip các file XML (lưu không nén).
 */
export type XlsxCell = string | number | null | undefined;

const escapeXml = (value: string) =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    // Ký tự điều khiển không hợp lệ trong XML
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "");

/** 0 → A, 25 → Z, 26 → AA */
const columnName = (index: number) => {
  let name = "";
  for (let n = index + 1; n > 0; n = Math.floor((n - 1) / 26)) name = String.fromCharCode(65 + ((n - 1) % 26)) + name;
  return name;
};

function sheetXml(header: string[], rows: XlsxCell[][], widths: number[]) {
  const cell = (value: XlsxCell, ref: string, style = 0) => {
    const s = style ? ` s="${style}"` : "";
    if (typeof value === "number" && Number.isFinite(value)) return `<c r="${ref}"${s}><v>${value}</v></c>`;
    if (value === null || value === undefined || value === "") return "";
    return `<c r="${ref}" t="inlineStr"${s}><is><t xml:space="preserve">${escapeXml(String(value))}</t></is></c>`;
  };
  const line = (values: XlsxCell[], rowIndex: number, style = 0) =>
    `<row r="${rowIndex}">${values.map((value, col) => cell(value, `${columnName(col)}${rowIndex}`, style)).join("")}</row>`;
  const cols = widths.map((width, index) => `<col min="${index + 1}" max="${index + 1}" width="${width}" customWidth="1"/>`).join("");
  return (
    `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` +
    `<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">` +
    `<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>` +
    `<cols>${cols}</cols>` +
    `<sheetData>${line(header, 1, 1)}${rows.map((row, index) => line(row, index + 2)).join("")}</sheetData>` +
    (rows.length ? `<autoFilter ref="A1:${columnName(header.length - 1)}${rows.length + 1}"/>` : "") +
    `</worksheet>`
  );
}

